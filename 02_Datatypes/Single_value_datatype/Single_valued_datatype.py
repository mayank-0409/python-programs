# Datetype represents the type of data present inside a variable.

# 1. Integer - Any real number without decimal point [whole number] 
# Default value is 0
a = 10
print(type(a))

# 2. Float - Any real number with decimal point
# Default value is 0.0
a = 1.0
print(type(a))

# 3. Complex - It is a combination of real number and imaginary number. Complex is in form of [ A + Bj ]
# Default value is 0j
a = 1.0 + 2j
print(type(a))

# Boolean - The only value allowed for this datatype are True and False  
# Default value is False
a = True
print(type(a))